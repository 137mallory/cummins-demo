# INTERNAL-ENDPOINT GATE. ops/lineage/bench/twin are operator-only (they expose the schema map,
# file/function layout, row counts and per-doc lineage — a blueprint, not client data). The client
# frontend only ever calls /api/dataset, /api/img, /api/pulse, so gating these prefixes never
# touches it. Enforced ONLY when OPS_TOKEN is set (prod), so local/dev without the env stays open.
# Token accepted via X-Ops-Token header, ?token=, or an ops_token cookie (the internal twin sends
# the header). Unset OPS_TOKEN → no gate.
_OPS_TOKEN = os.environ.get("OPS_TOKEN", "").strip()
_INTERNAL_PREFIXES = ("/api/ops", "/api/lineage", "/api/bench", "/api/twin")

@app.middleware("http")
async def _gate_internal_endpoints(request, call_next):
    if _OPS_TOKEN and request.method != "OPTIONS":
        p = request.url.path
        if any(p == pre or p.startswith(pre + "/") for pre in _INTERNAL_PREFIXES):
            tok = (request.headers.get("x-ops-token")
                   or request.query_params.get("token")
                   or request.cookies.get("ops_token") or "")
            if tok != _OPS_TOKEN:
                return JSONResponse(status_code=403,
                                    content={"error": "internal ops endpoint — token required"})
    return await call_next(request)

