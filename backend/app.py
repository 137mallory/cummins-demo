def _doc_for_url(cur, url):
    """The KSSL document_id for a source URL, or None when that article was never synced."""
    if not url:
        return None
    try:
        cur.execute("SELECT document_id FROM public.documents WHERE url=%s LIMIT 1", (url,))
        r = cur.fetchone()
        if not r:
            return None
        return r["document_id"] if isinstance(r, dict) else r[0]
    except Exception:
        return None


def _source_doc_ids(cur, table, id_col, id_val):
    """source_doc_ids for an enrichment row, guarded against a missing table/column (older DBs)."""
    if not id_val or not _regclass(cur, table):
        return []
    try:
        cur.execute("SELECT source_doc_ids FROM " + table + " WHERE " + id_col + "=%s", (id_val,))
        r = cur.fetchone()
        v = (r.get("source_doc_ids") if isinstance(r, dict) else (r[0] if r else None))
        return [str(x) for x in v] if v else []
    except Exception:
        return []


def _name_variants(term):
    """Lowercased spellings of a name to match on -- '-' vs ' ' vs '' -- so 'RUDRAM-II' finds
    'Rudram II' too. Equality only (the index is btree on lower(text), and a leading-wildcard LIKE
    would be a seq scan over ~82M spans)."""
    t = " ".join((term or "").strip().lower().split())
    if len(t) < 3:
        return []
    v = {t, t.replace("-", " "), t.replace("-", ""), t.replace(" ", "-"), t.replace(" ", "")}
    return [x for x in v if len(x) >= 3]


def _docs_mentioning(cur, term, limit=20):
    """Reconstruct which corpus documents NAME a thing, for enrichment rows whose source docs were
    never recorded. Exact match on extracted.span.lower(text) (index-backed, ~0.03s) + one evidence
    quote from a matching proposition. Returns (document_ids, sample_quote). Never a leading-wildcard
    scan; statement_timeout is set by the caller so it can never hang the endpoint."""
    vs = _name_variants(term)
    if not vs:
        return [], None
    try:
        cur.execute("SELECT DISTINCT document_id FROM extracted.span WHERE lower(text) = ANY(%s) LIMIT %s",
                    (vs, limit))
        docs = [(r["document_id"] if isinstance(r, dict) else r[0]) for r in cur.fetchall()]
        quote = None
        if docs:
            cur.execute("SELECT ev_quote FROM extracted.proposition "
                        "WHERE lower(subject) = ANY(%s) AND ev_quote IS NOT NULL LIMIT 1", (vs,))
            r = cur.fetchone()
            quote = (r["ev_quote"] if isinstance(r, dict) else r[0]) if r else None
        return docs, quote
    except Exception:
        return [], None


@app.get("/api/lineage/entity")
def lineage_entity(type: str, id: str = None, cid: str = None, field: str = None,
                   url: str = None, name: str = None):
    """Universal 'trace any UI value to its origin' resolver. Returns a normalized envelope with an
    HONEST provenance class -- recorded (single raw->signal document trace), recorded_partial
    (enrichment built from N corpus documents, each drillable), reconstructed (a source URL,
    resolvable to a document when that article is in the corpus), curated (hand-audited source_url +
    verbatim quote), external / unavailable (no corpus lineage -- stated plainly, never faked).
    Read-only. Gated with the other /api/lineage/* endpoints."""
    t = (type or "").strip().lower()
    try:
        conn = _ops_conn()
    except Exception as exc:
        return JSONResponse(status_code=503, content={"error": "db unavailable", "detail": str(exc)})
    try:
        cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
        try:
            cur.execute("SET statement_timeout='6000'")   # no corpus search can ever hang the trace
        except Exception:
            pass

        def env(cls, summary, evidence=None, documents=None, trace=None, gaps=None):
            return JSONResponse({
                "entity": {"type": t, "id": id, "cid": cid, "field": field,
                           "label": name or field or id or cid},
                "class": cls, "summary": summary, "evidence": evidence or [],
                "documents": documents or [], "trace": trace, "gaps": gaps or []})

        # doc-backed: a signal card (id == pl_<doc>) or a patent (id == doc_id) -> full chain
        if t in ("signal", "card", "patent"):
            did = id[3:] if (id or "").startswith("pl_") else id
            if not did:
                return JSONResponse(status_code=400, content={"error": "id required"})
            _code, body = build_lineage(cur, did)
            return env("recorded" if t != "patent" else "reconstructed",
                       "Traced to the raw crawled document and every extraction / LLM hop below.",
                       documents=[did], trace=body, gaps=body.get("known_gaps"))

        # url-reconstructed: news / innovation -> resolve its article URL to a document, then trace
        if t in ("news", "innovation"):
            did = _doc_for_url(cur, url)
            if did:
                _code, body = build_lineage(cur, did)
                return env("reconstructed",
                           "Its source article is in the KSSL corpus, so it traces to the raw document.",
                           evidence=[{"kind": "source", "url": url}], documents=[did],
                           trace=body, gaps=body.get("known_gaps"))
            return env("reconstructed",
                       "Synthesised from the cited source; that article is not in the KSSL document "
                       "corpus, so there is no single raw->signal trace. The source URL is the provenance.",
                       evidence=[{"kind": "source", "url": url}] if url else [])

        # enrichment many-to-one: matchup / partner -> the corpus documents that built it
        if t in ("matchup", "partner"):
            table, col = ("serving.matchup", "matchup_id") if t == "matchup" else ("serving.partner", "id")
            dids = _source_doc_ids(cur, table, col, id)
            if dids:
                trace = build_lineage(cur, dids[0])[1] if len(dids) == 1 else None
                return env("recorded_partial",
                           "Built from %d corpus document%s; each is drillable to raw below."
                           % (len(dids), "" if len(dids) == 1 else "s"),
                           documents=dids, trace=trace)
            return env("seeded",
                       "A revived / reference row with no recorded source documents -- no corpus lineage.",
                       evidence=[{"kind": "source", "url": url}] if url else [])

        # curated competitor field: the hand-audited source URL + the verbatim line it was read from
        if t == "field":
            ev = ((COMPANY_PROVENANCE.get(cid) or {}).get(field) or {})
            if ev.get("source_url") or ev.get("quote"):
                return env("curated",
                           "Hand-audited value, cited to a primary source with the verbatim line it "
                           "was read from.",
                           evidence=[{"kind": "quote", "url": ev.get("source_url"),
                                      "quote": ev.get("quote"), "value": ev.get("value"),
                                      "fy": ev.get("fy")}])
            return env("unavailable",
                       "Produced by the pipeline's enrichment with no per-field document lineage recorded.",
                       gaps=["enrichment competitor fields carry no source_doc_ids"])

        # product / spec: curated file first; else RECONSTRUCT from the corpus. The enrich step wrote
        # the product from documents but never recorded which -- so we find the corpus documents whose
        # extracted spans NAME it. That is honest provenance (reconstructed, not recorded).
        if t == "product":
            prod = next((p for p in (PRODUCTS_OVERLAY.get(cid) or [])
                         if str(p.get("name", "")).strip().lower() == str(name or "").strip().lower()), None)
            if prod and prod.get("source_url"):
                return env("curated", "Curated product entry, cited to its source.",
                           evidence=[{"kind": "source", "url": prod.get("source_url")}])
            docs, quote = _docs_mentioning(cur, name)
            if docs:
                trace = build_lineage(cur, docs[0])[1] if len(docs) == 1 else None
                return env("reconstructed",
                           "The enrich step wrote this product from the corpus but did not record which "
                           "documents. These %d corpus document%s name it (matched on the product name in "
                           "the extraction spans) and each is drillable to raw." % (len(docs), "" if len(docs) == 1 else "s"),
                           evidence=[{"kind": "quote", "quote": quote}] if quote else [],
                           documents=docs, trace=trace,
                           gaps=["product→document link not recorded by the enrich step; reconstructed by name match"])
            return env("unavailable",
                       "No curated source, and the product name is not found in the extraction corpus.")

        # honestly no corpus lineage -- stated, not faked
        if t in ("geo", "tender", "leadership", "source"):
            return env("external", {
                "geo": "Geographic presence carries a per-row source URL only; no document lineage.",
                "tender": "Sourced from a government tender portal / API, not the KSSL corpus -- the "
                          "portal URL is the provenance.",
                "leadership": "Harvested per-value from the company's own pages (URL + line); no corpus "
                              "document lineage.",
                "source": "A source-registry entry -- a URL, with no upstream document lineage.",
            }.get(t, "No corpus lineage."), evidence=[{"kind": "source", "url": url}] if url else [])

        return JSONResponse(status_code=400, content={"error": "unknown entity type", "type": t})
    finally:
        conn.close()


