# THE IMPACT SENTENCE THAT TOLD KSSL WHAT TO DO. Until 2026-09-16 gen_signal_text asked the
# model for "how KSSL could act on this (export, partner, or bid)" and "how KSSL could adopt
# or learn from it", and it answered with advice it had no facts for -- "KSSL could capitalize
# on this by exporting ammunition to Ukraine". The prompts now ask for the facts instead, and
# the kinds those two reads wrote are retired. Rows carrying them predate the change: the
# sentence is not served, and the panel falls back to its own text until the next enrich pass
# regenerates the row. Dropping it here rather than in the database keeps this a read-side
# decision that needs no migration and no write to a serving table.
RETIRED_IMPACT_KINDS = frozenset(["opportunity", "adoptable"])


def _emit(row, fields, optional=frozenset()):
    out = {}
    stale_impact = row["ksslImpactKind"] in RETIRED_IMPACT_KINDS \
        if "ksslImpactKind" in fields else False
    for f in fields:
        v = row[f]
        if stale_impact and f in ("ksslImpact", "ksslImpactKind"):
            continue
        if v is None and f in optional:
            continue
        if f == "extra":
            for k, x in v.items():
                out.setdefault(k, x)
            continue
        if v is None and f in ARRAY_FIELDS:
            v = []
        out[f] = v
    return out



