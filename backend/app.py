def _blank(v):
    return v is None or v == [] or v == {} or (isinstance(v, str) and not v.strip())


def _product_key(p):
    """"RCH-155" == "RCH 155" == "rch&amp;155"; "" for a name with no letters or digits (never matched)."""
    return re.sub(r"[^a-z0-9]+", "", html.unescape(html.unescape(p["name"])).casefold())


# ONE PRODUCT, MANY NAMES. The curated catalogue writes "ARCHER Mobile Howitzer", "M777
# Lightweight Towed Howitzer", "Naval Strike Missile (NSM)"; articles write "Archer", "M777",
# "NSM". The exact key matched 94 of 579 curated products on staging (2026-09-18), so the
# rest were served twice -- once with curated specs, once with enriched ones -- and never
# merged. A second pass matches on a model DESIGNATOR (letters+digits: cv90, m777, rch155,
# pzh2000) or on the leading NAME word ("archer"), and only when exactly ONE curated product
# qualifies, so a bare brand shared by several variants (BrahMos, BrahMos-NG, BrahMos-ER)
# never collapses them into one.
_SIZE_TOKEN = re.compile(r"^\d+(?:mm|cm|m|x\d+|×\d+)$")
_GENERIC_HEAD = {"the", "new", "next", "advanced", "light", "heavy", "medium", "mobile", "naval",
                 "combat", "armoured", "armored", "guided", "air", "anti", "multi", "self",
                 "long", "short", "high", "family", "system", "systems", "mk"}


def _designators(name):
    words = re.findall(r"[A-Za-z0-9]+", html.unescape(html.unescape(str(name or ""))).casefold())
    out = set()
    for i, w in enumerate(words):
        if re.search(r"[a-z]", w) and re.search(r"\d", w) and not _SIZE_TOKEN.match(w):
            out.add(w)                                    # cv90, m777, k9, m109a7
        if (i + 1 < len(words) and re.fullmatch(r"[a-z]{2,5}", w) and w not in _GENERIC_HEAD
                and re.fullmatch(r"\d{2,4}", words[i + 1])):
            out.add(w + words[i + 1])                     # "RCH 155" -> rch155, "PzH 2000"
    return out


def _name_head(name):
    words = re.findall(r"[A-Za-z0-9]+", html.unescape(html.unescape(str(name or ""))).casefold())
    return words[0] if words and len(words[0]) >= 4 and words[0].isalpha() \
        and words[0] not in _GENERIC_HEAD else ""


def _loose_match(p, pool):
    """The one curated product in `pool` that is the same product as stored product `p`
    by designator or leading name word, or None when there is no single answer."""
    k, d, h = _product_key(p), _designators(p["name"]), _name_head(p["name"])
    hits = []
    for ck, c in pool.items():
        cd, ch = _designators(c["name"]), _name_head(c["name"])
        if (d and cd and d & cd) or (ch and ch == k) or (h and h == ck):
            hits.append(ck)
    return hits[0] if len(hits) == 1 else None


def _products(items, origin, allow_names):
    """Named product objects, deep-copied so the served row never aliases a curated global."""
    out = []
    for p in items if isinstance(items, list) else []:
        if allow_names and isinstance(p, str):
            p = {"name": p}
        if not isinstance(p, dict) or _blank(p.get("name")) or not isinstance(p["name"], str):
            continue
        p = copy.deepcopy(p)
        if origin == "curated":
            p["origin"] = "curated"
        else:
            p.setdefault("origin", origin)
        out.append(p)
    return out


def _newest_year(v):
    """The most recent year named anywhere in a value ("FY2025", "2,530 crore (2024-25)")."""
    yrs = re.findall(r"(?<!\d)((?:19|20)\d\d)(?!\d)", json.dumps(v, default=str)) if v else []
    return max(yrs, default="0")


def _sales_rows(v):
    """A revenue value in the one shape the Profile page renders: [{value, detail, url, line}].

    company_overrides.json (and the workbook writer) store {text, fy, srcs}, and the page keeps
    only list rows carrying value, url and line -- so 32 curated revenue figures rendered as "—".
    Same figure, same source, readable shape. Anything else passes through unchanged."""
    if isinstance(v, dict) and not _blank(v.get("text")):
        srcs = v.get("srcs") if isinstance(v.get("srcs"), list) else []
        url = next((x if isinstance(x, str) else (x or {}).get("url") for x in srcs), None)
        return [{"value": v["text"], "detail": v.get("fy"), "url": url, "line": v["text"]}]
    return v


# ONE SPEC FIELD, MANY LABELS. The curated file writes "Maximum speed", "Combat weight",
# "Operational range"; the enrichment writes "Max speed", "Weight", "Range". Matched by meaning,
# so a product never shows the same measurement twice under two names.
_SPEC_SYNONYMS = {
    "caliber": "calibre", "maximum range": "range", "max range": "range",
    "effective range": "range", "operational range": "range", "firing range": "range",
    "maximum speed": "max speed", "speed": "max speed", "top speed": "max speed",
    "combat weight": "weight", "empty weight": "weight", "mass": "weight",
    "overall length": "length", "engine power": "power", "power output": "power",
    "payload capacity": "payload", "rate of fire": "rate of fire", "diving depth": "diving depth",
}


def _spec_key(label):
    k = re.sub(r"\s+", " ", str(label or "").strip().casefold())
    return _SPEC_SYNONYMS.get(k, k)


def _merge_specs(stored, curated):
    """Per-field spec merge -> (specs, origins, also_reported).

    The curated value wins wherever the curated file has that field: it is hand-audited. A
    stored (enriched) value for the same field that says something else is not thrown away; it
    is returned as also_reported, so the page can say "also reported: 400 km". Fields the curated
    file lacks keep the stored value. Measured 2026-09-18: 84% of shared fields agree, and about
    one conflict in ten is the curated value being wrong -- which is why the other value stays
    visible."""
    stored = stored if isinstance(stored, dict) else {}
    curated = curated if isinstance(curated, dict) else {}
    specs, origins, also = {}, {}, {}
    by_key = {}
    for k, v in curated.items():
        if not _blank(v):
            specs[k], origins[k] = v, "curated"
            by_key.setdefault(_spec_key(k), k)
    for k, v in stored.items():
        if _blank(v):
            continue
        ck = by_key.get(_spec_key(k))
        if ck is None:
            specs[k], origins[k] = v, "pipeline"
        elif str(v).strip().casefold() != str(specs[ck]).strip().casefold():
            also[ck] = v
    return specs, origins, also


def apply_curated(row, fields, products, mode=OVERRIDES_MODE, products_mode=None):
    """Overlay one competitor's curated fields and products onto its served row, in place.
    `products_mode` defaults to `mode` when called with an explicit mode, else PRODUCTS_MODE."""
    origins = row.setdefault("origins", {})
    fallback = str(mode or "").strip().lower() == "fallback"     # anything else is today's behaviour
    if products_mode is None:
        products_mode = mode if mode is not OVERRIDES_MODE else PRODUCTS_MODE
    fields = fields if isinstance(fields, dict) else {}
    for k in _OVERRIDE_FIELDS:
        mine, theirs = row.get(k), fields.get(k)
        if _blank(theirs) or (fallback and not _blank(mine)):
            if not _blank(mine):
                origins[k] = "pipeline"
            continue
        if k in ("sales", "company_size") and _newest_year(mine) > _newest_year(theirs):
            # THE NEWER FIGURE WINS. The curated file is hand-written and ages: the fact check
            # of 2026-09-20 found 29 stale values, every one a revenue or headcount the company
            # has since restated (Babcock FY25 while FY26 was published, NORINCO 2016-2021).
            origins[k] = "pipeline"
            continue
        row[k] = copy.deepcopy(theirs)
        origins[k] = "curated"
    if "sales" in row:
        row["sales"] = _sales_rows(row["sales"])

    curated, seen = [], set()
    for p in _products(products, "curated", allow_names=False):
        key = _product_key(p)
        if key and key in seen:
            continue                          # the file listing one product twice serves it once
        seen.add(key)
        curated.append(p)
    had = "products" in row and row["products"] is not None
    stored = _products(row.get("products"), "pipeline", allow_names=True)
    if str(products_mode or "").strip().lower() == "enriched":
        # Specs from the enrichment pipeline only: no curated file, and none of the older
        # hand/agent-filled spec values stored on pipeline products. A value is enriched when
        # the projection recorded its document count (specDocs). One such value is enough to
        # list the product -- project_enrichment's 2026-09-21 floor: a single real spec is OUR
        # record being incomplete, so it is shown and marked `incomplete` (fewer than 2), not
        # hidden. This used to require 2 and silently undid that decision (~324 products).
        out = []
        for p in stored:
            docs = p.get("specDocs") if isinstance(p.get("specDocs"), dict) else {}
            specs = {k: v for k, v in (p.get("specs") or {}).items() if k in docs and not _blank(v)}
            if specs:
                p["specs"] = specs
                p["incomplete"] = len(specs) < 2
                p["specsAlsoReported"] = {k: v for k, v in (p.get("specsAlsoReported") or {}).items()
                                          if k in specs}
                p.pop("enrichedSpecs", None)
                out.append(p)
        row["products"] = out
        return row
    if not curated:
        if had:
            row["products"] = stored
        return row
    if str(products_mode or "").strip().lower() != "fallback":
        row["products"] = curated
        return row
    unused = {_product_key(p): p for p in curated if _product_key(p)}
    for p in stored:
        match = unused.pop(_product_key(p), None) if _product_key(p) else None
        if match is None and _product_key(p):
            lk = _loose_match(p, unused)
            if lk is not None:
                match = unused.pop(lk)
                p.setdefault("fieldOrigins", {})["matchedCurated"] = match.get("name")
        for f, v in (match or {}).items():
            if f == "specs":
                # per field, not the whole dict: a stored product with ONE spec used to hide
                # every curated spec of the same product
                merged, spec_origins, also = _merge_specs(p.get("specs"), v)
                if merged:
                    p["specs"] = merged
                    p["specOrigins"] = spec_origins
                    kinds = set(spec_origins.values())
                    if "curated" in kinds:
                        p.setdefault("fieldOrigins", {})["specs"] = (
                            "curated" if kinds == {"curated"} else "merged")
                    if also:                  # added to the projection's own alternates
                        p["specsAlsoReported"] = dict(p.get("specsAlsoReported") or {}, **also)
                continue
            if f != "origin" and _blank(p.get(f)) and not _blank(v):
                p[f] = v
                p.setdefault("fieldOrigins", {})[f] = "curated"
    row["products"] = stored + [p for p in curated if not _product_key(p) or _product_key(p) in unused]
    # A CATALOGUE ENTRY CARRIES A SPEC SHEET. Every curated product has one and the projection
    # now stores enriched products only with 2+ fields; what was left empty were 151 older
    # pipeline stubs (name only), which read on the Products page as products with no specs.
    # Served, not deleted: the rows stay in the database.
    row["products"] = [p for p in row["products"]
                       if p.get("origin") == "curated" or not _blank(p.get("specs"))]
    return row

