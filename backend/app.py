@app.get("/api/img")
def img_proxy(u: str = ""):
    """Image proxy. Many publishers block hotlinking (Referer/UA checks), so a good
    og:image 403s in a bare <img> on the dashboard. This refetches it server-side with
    a browser UA and no referer and streams it back from our own origin. Frontend Thumb
    routes every http(s) image through here (see thumb/Thumb.jsx proxied()). Stdlib only.

    SSRF-guarded: http(s) only, the host must resolve to a PUBLIC address (no loopback/
    private/link-local), the response must be image/*, capped at 6 MB and 12s."""
    import re as _re, socket as _sock, ipaddress as _ip
    import urllib.request as _ur, urllib.parse as _up
    from fastapi.responses import Response, JSONResponse as _J

    if not u or not _re.match(r"^https?://", u, _re.I):
        return _J(status_code=400, content={"error": "bad url"})
    host = (_up.urlparse(u).hostname or "").strip()
    try:
        infos = _sock.getaddrinfo(host, None)
        for _fam, _t, _p, _c, sockaddr in infos:
            addr = _ip.ip_address(sockaddr[0])
            if addr.is_private or addr.is_loopback or addr.is_link_local or addr.is_reserved or addr.is_multicast:
                return _J(status_code=400, content={"error": "blocked host"})
    except Exception:
        return _J(status_code=400, content={"error": "unresolvable host"})

    req = _ur.Request(u, headers={
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                      "(KHTML, like Gecko) Chrome/120.0 Safari/537.36",
        "Accept": "image/*,*/*;q=0.8",
    })
    try:
        with _ur.urlopen(req, timeout=12) as r:
            ct = (r.headers.get("Content-Type") or "").split(";")[0].strip().lower()
            if not ct.startswith("image/"):
                return _J(status_code=404, content={"error": "not an image"})
            data = r.read(6 * 1024 * 1024 + 1)
            if len(data) > 6 * 1024 * 1024:
                return _J(status_code=413, content={"error": "too large"})
    except Exception:
        return _J(status_code=404, content={"error": "fetch failed"})
    return Response(content=data, media_type=ct,
                    headers={"Cache-Control": "public, max-age=86400"})


