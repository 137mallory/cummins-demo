# GET /api/pulse -- live company pulse: stock quote (Yahoo Finance chart API,
# keyless) + trending headlines (Google News RSS, keyless). Server-side fetch so
# the browser only talks to its own origin. Mirrors frontend/src/lib/pulseFetch.js
# and tickers.js. Grounding: only directly-listed entities carry a ticker; a dead
# feed yields null/[] and the card says so. No LLM, safe to run on the VPS.
# ---------------------------------------------------------------------------
