"""Competitor Moment's deeper analysis: <pack>/competitor_news_lenses.json -> frontend/src/lib/newsLenses.js.

Each competitor news item (by its card id) carries 3 to 5 lens entries (Supply chain, Manufacturing and capacity,
Market and demand, ...) written from the article itself, or from its summary when the page could not be read
(`basis`). The text states what the article says and marks an inference; nothing here adds a fact the item lacks.

    python db/news_lenses.py <competitor_news_lenses.json> <frontend/src/lib/newsLenses.js>
"""
import json
import re
import sys

VIEWS = ["Supply chain", "Manufacturing and capacity", "Market and demand", "Competitive position",
         "Commercial and pricing", "Technology and product", "Risks and what to watch"]
BANNED = re.compile(r"\b(KSSL|Action:)|—", re.I)


def check(data):
    for card, e in data.items():
        assert e.get("basis") in ("article", "summary"), f"{card}: basis"
        assert 3 <= len(e.get("lenses", [])) <= 5, f"{card}: {len(e.get('lenses', []))} lenses"
        for l in e["lenses"]:
            assert l["view"] in VIEWS, f"{card}: view {l['view']}"
            assert 40 <= len(l["text"]) <= 900, f"{card}: {l['view']} text length {len(l['text'])}"
            assert not BANNED.search(l["text"]), f"{card}: banned wording in {l['view']}"
    return data


if __name__ == "__main__":
    if len(sys.argv) < 3:
        check({"c": {"basis": "summary", "lenses": [{"view": v, "text": "Cat says orders strained capacity, which suggests longer lead times."} for v in VIEWS[:3]]}})
        print("ok")
        sys.exit()
    data = check(json.load(open(sys.argv[1], encoding="utf-8")))
    js = ("/** COMPETITOR NEWS LENSES: generated by db/news_lenses.py from <pack>/competitor_news_lenses.json. Do not edit by hand.\n"
          " *  Keyed by the news item's card id; basis says whether the article or only its summary was read. */\n\n"
          f"export const NEWS_LENSES = {json.dumps(data, indent=2, ensure_ascii=False)};\n")
    open(sys.argv[2], "w", encoding="utf-8").write(js)
    print(f"{len(data)} items -> {sys.argv[2]}")
